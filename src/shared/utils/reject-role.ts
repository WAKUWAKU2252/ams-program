// ═══════════════════════════════════════════════════════════════════════════
// แปล role ของคนที่กดตีกลับเป็นภาษาคน - นิยามที่เดียวของทั้งระบบ
//
// ใช้สองที่: note ในตาราง (RequestTable) และแถบเตือนในกล่องกรอก (AssetFormDialog)
// ถ้าแยกกันนิยาม วันที่เพิ่ม role ใหม่จะแปลที่เดียวแล้วอีกที่โชว์ค่าดิบ โดยไม่มีอะไรฟ้อง
//
// role ที่ backend ส่งมาเป็น snapshot ณ ตอนกด (asset.rejectedRole / asset_request.rejectedRole)
// ไม่ใช่ role ปัจจุบันของคนนั้น - คนย้ายตำแหน่งแล้วประวัติจะไม่เพี้ยนย้อนหลัง
//
// ★ ทำไมต้องแปล ไม่โชว์ 'ADMIN' ดิบ ๆ: role บอกว่า "ต้องแก้แบบไหน" ซึ่งต่างกันคนละเรื่อง
//   MANAGER      = ตีกลับทั้งใบ ผู้ขอต้องแก้แล้วกดส่งคำขอใหม่
//   FINANCE/ADMIN = ตีกลับรายชิ้น แก้แล้วชิ้นนั้นกลับเข้าคิวออกเลขเอง ไม่ต้องส่งใหม่
// ═══════════════════════════════════════════════════════════════════════════

const LABEL: Record<string, string> = {
  MANAGER: 'หัวหน้า',
  FINANCE: 'บัญชี',
  ADMIN: 'แอดมิน',
}

/**
 * ชื่อภาษาไทยของ role - role ที่ไม่รู้จักคืนค่าดิบกลับไป ไม่ใช่คืนค่าว่าง
 * (ถ้าวันหลังมี role ใหม่ อย่างน้อยผู้ใช้ยังเห็นว่ามีค่าอะไรอยู่ ดีกว่าช่องหายไปเฉย ๆ
 *  แล้วไม่มีใครรู้ว่าข้อมูลขาดหรือระบบไม่รู้จักค่านั้น)
 */
export function rejectRoleLabel(role: string | null | undefined): string {
  if (!role) return ''
  return LABEL[role] ?? role
}
